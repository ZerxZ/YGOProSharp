using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace YGOProSharp.Generators;

/// <summary>
/// Roslyn 增量源生成器：在编译期收集所有标注了 <c>[Deck(...)]</c> 的 WindBot C# 卡组执行器，
/// 为 <c>DecksManager</c> 生成强类型工厂委托数组，彻底消除启动时 <c>Assembly.GetTypes()</c> 全量反射与运行时 <c>Activator.CreateInstance</c>。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class WindBotDeckRegistryGenerator : IIncrementalGenerator
{
    private const string DeckAttributeMetadataName = "WindBot.Game.AI.DeckAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<DeckRegistrationModel?> items = context.SyntaxProvider.ForAttributeWithMetadataName(
            DeckAttributeMetadataName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => ExtractDeck(ctx))
            .Where(static x => x is not null);

        context.RegisterSourceOutput(items.Collect(), static (spc, list) =>
        {
            if (list.IsDefaultOrEmpty)
                return;

            StringBuilder sb = new(list.Length * 160 + 512);
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("namespace WindBot.Game.AI");
            sb.AppendLine("{");
            sb.AppendLine("    public static partial class DecksManager");
            sb.AppendLine("    {");
            sb.AppendLine("        private static DeckEntry[] CreateGeneratedDecks() =>");
            sb.AppendLine("        [");

            foreach (DeckRegistrationModel? item in list.OrderBy(static d => d?.Name, StringComparer.OrdinalIgnoreCase))
            {
                if (item is null)
                    continue;

                sb.Append("            new DeckEntry(")
                  .Append(SymbolDisplay.FormatLiteral(item.Name, quote: true)).Append(", ")
                  .Append(SymbolDisplay.FormatLiteral(item.File, quote: true)).Append(", ")
                  .Append(SymbolDisplay.FormatLiteral(item.Level, quote: true)).Append(", ")
                  .Append("static (ai, duel) => new ").Append(item.TypeFullName).AppendLine("(ai, duel)),");
            }

            sb.AppendLine("        ];");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            spc.AddSource("DecksManager.Registry.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    private static DeckRegistrationModel? ExtractDeck(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol typeSymbol || typeSymbol.IsAbstract)
            return null;

        AttributeData? attr = ctx.Attributes.FirstOrDefault();
        if (attr is null || attr.ConstructorArguments.Length == 0)
            return null;

        string? name = attr.ConstructorArguments[0].Value as string;
        if (string.IsNullOrWhiteSpace(name))
            return null;

        string? file = attr.ConstructorArguments.Length > 1 ? attr.ConstructorArguments[1].Value as string : null;
        if (string.IsNullOrEmpty(file))
            file = name;

        string level = (attr.ConstructorArguments.Length > 2 ? attr.ConstructorArguments[2].Value as string : null) ?? "Normal";
        string fullTypeName = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        return new DeckRegistrationModel(name!, file!, level, fullTypeName);
    }

    private sealed record DeckRegistrationModel(
        string Name,
        string File,
        string Level,
        string TypeFullName);
}
