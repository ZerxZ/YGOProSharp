using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace YGOProSharp.Generators;

/// <summary>
/// Roslyn 增量源生成器：在编译期扫描 <c>WindBot.Game.AI.Executor</c> 虚钩子、<c>DefaultExecutor</c> 内置布尔规则与游戏枚举，
/// 自动生成 <c>LuaDeckExecutor</c> 覆写方法、<c>LuaDeckDsl</c> 全局钩子绑定、<c>LuaDeckHookNames</c> 常量表与零反射枚举常量字典。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LuaExecutorBindingGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = "WindBot.Game.AI.Lua.GenerateLuaExecutorBindingsAttribute";

    private const string AttributeSource = """
        // <auto-generated />
        using System;

        namespace WindBot.Game.AI.Lua
        {
            [AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
            internal sealed class GenerateLuaExecutorBindingsAttribute : Attribute
            {
            }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
            ctx.AddSource("GenerateLuaExecutorBindingsAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        IncrementalValuesProvider<LuaBindingModel?> models = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeFullName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, ct) => ExtractModel(ctx, ct))
            .Where(static m => m is not null);

        context.RegisterSourceOutput(models, static (spc, model) =>
        {
            if (model is null)
                return;

            spc.AddSource("LuaDeckHookNames.g.cs", SourceText.From(EmitHookNames(model), Encoding.UTF8));
            spc.AddSource("LuaDeckDsl.Hooks.g.cs", SourceText.From(EmitDslHooks(model), Encoding.UTF8));
            spc.AddSource("LuaDeckExecutor.Bindings.g.cs", SourceText.From(EmitExecutorBindings(model), Encoding.UTF8));
        });
    }

    private static LuaBindingModel? ExtractModel(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol targetClass)
            return null;

        INamedTypeSymbol? defaultExecutor = targetClass.BaseType;
        INamedTypeSymbol? baseExecutor = defaultExecutor?.BaseType;
        if (defaultExecutor is null || baseExecutor is null)
            return null;

        // 1. 提取 Executor 上所有 public virtual On* 决策/事件虚方法
        ImmutableArray<HookMethodModel>.Builder hooks = ImmutableArray.CreateBuilder<HookMethodModel>();
        foreach (ISymbol member in baseExecutor.GetMembers())
        {
            ct.ThrowIfCancellationRequested();
            if (member is not IMethodSymbol method ||
                method.MethodKind != MethodKind.Ordinary ||
                method.DeclaredAccessibility != Accessibility.Public ||
                !method.IsVirtual ||
                !method.Name.StartsWith("On", StringComparison.Ordinal))
            {
                continue;
            }

            ImmutableArray<HookParamModel>.Builder parameters = ImmutableArray.CreateBuilder<HookParamModel>(method.Parameters.Length);
            foreach (IParameterSymbol p in method.Parameters)
            {
                parameters.Add(new HookParamModel(
                    p.Name,
                    p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    p.Type.TypeKind == TypeKind.Enum));
            }

            HookReturnKind returnKind = ClassifyReturnKind(method);
            string returnTypeFullName = method.ReturnsVoid
                ? "void"
                : method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            hooks.Add(new HookMethodModel(
                Name: method.Name,
                FieldName: "_on" + method.Name.Substring(2),
                SnakeName: ToSnakeCase(method.Name),
                ReturnKind: returnKind,
                ReturnTypeFullName: returnTypeFullName,
                Parameters: parameters.ToImmutable()));
        }

        // 2. 提取 DefaultExecutor 上所有无参 bool Default* / UniqueFaceup* 规则方法
        ImmutableArray<string>.Builder defaultRules = ImmutableArray.CreateBuilder<string>();
        HashSet<string> seenRules = new(StringComparer.Ordinal);
        foreach (ISymbol member in defaultExecutor.GetMembers())
        {
            ct.ThrowIfCancellationRequested();
            if (member is not IMethodSymbol m ||
                m.MethodKind != MethodKind.Ordinary ||
                m.IsStatic ||
                m.Parameters.Length != 0 ||
                m.ReturnType.SpecialType != SpecialType.System_Boolean ||
                m.DeclaredAccessibility is not (Accessibility.Protected or Accessibility.Public or Accessibility.ProtectedOrInternal))
            {
                continue;
            }

            if ((m.Name.StartsWith("Default", StringComparison.Ordinal) ||
                 m.Name.StartsWith("UniqueFaceup", StringComparison.Ordinal)) &&
                seenRules.Add(m.Name))
            {
                defaultRules.Add(m.Name);
            }
        }

        // 3. 提取暴露给 Lua 全局作用域的枚举常量表（编译期展开，零运行时反射）
        (string LuaGlobalName, string MetadataName)[] targetEnums =
        [
            ("ExecutorType", "WindBot.Game.AI.ExecutorType"),
            ("CardLocation", "YGOProSharp.Abstractions.Ocg.Enums.CardLocation"),
            ("CardPosition", "YGOProSharp.Abstractions.Ocg.Enums.CardPosition"),
            ("CardType", "YGOProSharp.Abstractions.Ocg.Enums.CardType"),
            ("CardAttribute", "YGOProSharp.Abstractions.Ocg.Enums.CardAttribute"),
            ("CardRace", "YGOProSharp.Abstractions.Ocg.Enums.CardRace"),
            ("DuelPhase", "YGOProSharp.Abstractions.Ocg.Enums.DuelPhase")
        ];

        ImmutableArray<EnumMapModel>.Builder enums = ImmutableArray.CreateBuilder<EnumMapModel>(targetEnums.Length);
        foreach ((string globalName, string metaName) in targetEnums)
        {
            INamedTypeSymbol? enumSym = ctx.SemanticModel.Compilation.GetTypeByMetadataName(metaName);
            if (enumSym is null || enumSym.TypeKind != TypeKind.Enum)
                continue;

            ImmutableArray<(string Name, int Value)>.Builder fields = ImmutableArray.CreateBuilder<(string, int)>();
            foreach (ISymbol member in enumSym.GetMembers())
            {
                if (member is IFieldSymbol f && f.HasConstantValue && f.ConstantValue is not null)
                {
                    int val = Convert.ToInt32(f.ConstantValue);
                    fields.Add((f.Name, val));
                }
            }
            enums.Add(new EnumMapModel(globalName, fields.ToImmutable()));
        }

        return new LuaBindingModel(hooks.ToImmutable(), defaultRules.ToImmutable(), enums.ToImmutable());
    }

    private static HookReturnKind ClassifyReturnKind(IMethodSymbol method)
    {
        if (method.ReturnsVoid)
            return HookReturnKind.Void;

        ITypeSymbol ret = method.ReturnType;
        if (ret.SpecialType == SpecialType.System_Boolean)
            return HookReturnKind.Bool;
        if (ret.SpecialType == SpecialType.System_Int32)
            return HookReturnKind.Int32;
        if (ret.SpecialType == SpecialType.System_UInt32)
            return HookReturnKind.UInt32;
        if (ret.TypeKind == TypeKind.Enum)
            return HookReturnKind.Enum;

        if (ret is INamedTypeSymbol named &&
            named.Name == "IList" &&
            named.TypeArguments.Length == 1 &&
            named.TypeArguments[0].Name == "ClientCard")
        {
            return HookReturnKind.CardList;
        }

        return HookReturnKind.TypedObject;
    }

    private static string EmitHookNames(LuaBindingModel model)
    {
        StringBuilder sb = new(2048);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("namespace WindBot.Game.AI.Lua");
        sb.AppendLine("{");
        sb.AppendLine("    public static partial class LuaDeckHookNames");
        sb.AppendLine("    {");
        sb.AppendLine("        public const string OnInit = \"OnInit\";");
        sb.AppendLine("        public const string OnDispose = \"OnDispose\";");
        sb.AppendLine("        public const string OnReceivingAnnounceAlias = \"OnReceivingAnnounce\";");
        foreach (HookMethodModel h in model.Hooks)
        {
            sb.Append("        public const string ").Append(h.Name).Append(" = \"").Append(h.Name).AppendLine("\";");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitDslHooks(LuaBindingModel model)
    {
        StringBuilder sb = new(4096);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("namespace WindBot.Game.AI.Lua");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed partial class LuaDeckDsl");
        sb.AppendLine("    {");
        sb.AppendLine("        private void BindGeneratedHooks()");
        sb.AppendLine("        {");
        sb.AppendLine("            BindHook(\"on_init\", LuaDeckHookNames.OnInit);");
        sb.AppendLine("            BindHook(\"on_dispose\", LuaDeckHookNames.OnDispose);");

        foreach (HookMethodModel h in model.Hooks)
        {
            sb.Append("            BindHook(\"").Append(h.SnakeName).Append("\", LuaDeckHookNames.").Append(h.Name).AppendLine(");");
            if (h.Name == "OnPreBattleBetween")
                sb.AppendLine("            BindHook(\"on_pre_battle\", LuaDeckHookNames.OnPreBattleBetween);");
            else if (h.Name == "OnReceivingAnnouce")
                sb.AppendLine("            BindHook(\"on_receiving_announce\", LuaDeckHookNames.OnReceivingAnnouce);");
            else if (h.Name == "OnSelectYesNo")
                sb.AppendLine("            BindHook(\"on_select_yesno\", LuaDeckHookNames.OnSelectYesNo);");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitExecutorBindings(LuaBindingModel model)
    {
        StringBuilder sb = new(16384);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using YGOProSharp.Abstractions.Scripting;");
        sb.AppendLine();
        sb.AppendLine("namespace WindBot.Game.AI.Lua");
        sb.AppendLine("{");
        sb.AppendLine("    public partial class LuaDeckExecutor");
        sb.AppendLine("    {");

        // 1. 编译期生成的零反射枚举常量字典
        foreach (EnumMapModel em in model.Enums)
        {
            sb.Append("        private static readonly IReadOnlyDictionary<string, int> ").Append(em.LuaGlobalName).AppendLine("Constants =");
            sb.AppendLine("            new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase)");
            sb.AppendLine("            {");
            foreach ((string fName, int fVal) in em.Members)
            {
                sb.Append("                [\"").Append(fName).Append("\"] = ").Append(fVal).AppendLine(",");
            }
            sb.AppendLine("            }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);");
            sb.AppendLine();
        }

        // 2. 编译期生成的 DefaultExecutor 规则映射字典
        sb.AppendLine("        private static readonly FrozenDictionary<string, Func<LuaDeckExecutor, bool>> DefaultRuleMap =");
        sb.AppendLine("            new Dictionary<string, Func<LuaDeckExecutor, bool>>(StringComparer.OrdinalIgnoreCase)");
        sb.AppendLine("            {");
        foreach (string ruleName in model.DefaultRules)
        {
            sb.Append("                [\"").Append(ruleName).Append("\"] = static e => e.").Append(ruleName).AppendLine("(),");
        }
        sb.AppendLine("            }.ToFrozenDictionary(StringComparer.OrdinalIgnoreCase);");
        sb.AppendLine();

        // 3. 生命周期与决策钩子缓存字段
        sb.AppendLine("        private ILuaFunction _onInit;");
        sb.AppendLine("        private ILuaFunction _onDispose;");
        foreach (HookMethodModel h in model.Hooks)
        {
            sb.Append("        private ILuaFunction ").Append(h.FieldName).AppendLine(";");
        }
        sb.AppendLine();

        sb.AppendLine("        private void BindGeneratedEnumGlobals()");
        sb.AppendLine("        {");
        foreach (EnumMapModel em in model.Enums)
        {
            sb.Append("            _context.SetGlobal(\"").Append(em.LuaGlobalName).Append("\", ").Append(em.LuaGlobalName).AppendLine("Constants);");
        }
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.AppendLine("        private void ResolveGeneratedHooks()");
        sb.AppendLine("        {");
        sb.AppendLine("            _onInit = ResolveHook(LuaDeckHookNames.OnInit);");
        sb.AppendLine("            _onDispose = ResolveHook(LuaDeckHookNames.OnDispose);");
        foreach (HookMethodModel h in model.Hooks)
        {
            if (h.Name == "OnReceivingAnnouce")
            {
                sb.AppendLine("            _onReceivingAnnouce = ResolveHook(LuaDeckHookNames.OnReceivingAnnouce) ?? ResolveHook(LuaDeckHookNames.OnReceivingAnnounceAlias);");
            }
            else
            {
                sb.Append("            ").Append(h.FieldName).Append(" = ResolveHook(LuaDeckHookNames.").Append(h.Name).AppendLine(");");
            }
        }
        sb.AppendLine("        }");
        sb.AppendLine();

        // 4. 所有 Executor 虚方法覆写
        foreach (HookMethodModel h in model.Hooks)
        {
            string sigParams = string.Join(", ", h.Parameters.Select(static p => $"{p.TypeFullName} {p.Name}"));
            string baseCallArgs = string.Join(", ", h.Parameters.Select(static p => p.Name));
            string luaCallArgs = h.Parameters.Length == 0
                ? "this"
                : "this, " + string.Join(", ", h.Parameters.Select(static p => p.IsEnum ? $"(int){p.Name}" : p.Name));

            sb.Append("        public override ").Append(h.ReturnTypeFullName).Append(' ').Append(h.Name).Append('(').Append(sigParams).AppendLine(")");
            sb.AppendLine("        {");

            switch (h.ReturnKind)
            {
                case HookReturnKind.Void:
                    sb.Append("            base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    sb.Append("            if (").Append(h.FieldName).AppendLine(" != null)");
                    sb.Append("                InvokeVoid(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", ").Append(luaCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.Bool:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeBool(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out bool result, ").Append(luaCallArgs).AppendLine("))");
                    sb.AppendLine("                return result;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.Int32:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeInt(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out int result, ").Append(luaCallArgs).AppendLine("))");
                    sb.AppendLine("                return result;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.UInt32:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeObject(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out object raw, ").Append(luaCallArgs).AppendLine(") && LuaValueConverter.TryToUInt32(raw, out uint result))");
                    sb.AppendLine("                return result;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.Enum:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeObject(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out object raw, ").Append(luaCallArgs).Append(") && LuaValueConverter.TryToEnum(raw, out ").Append(h.ReturnTypeFullName).AppendLine(" result))");
                    sb.AppendLine("                return result;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.CardList:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeCardList(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out ").Append(h.ReturnTypeFullName).Append(" result, ").Append(luaCallArgs).AppendLine("))");
                    sb.AppendLine("                return result;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;

                case HookReturnKind.TypedObject:
                    sb.Append("            if (").Append(h.FieldName).Append(" != null && TryInvokeObject(").Append(h.FieldName).Append(", LuaDeckHookNames.").Append(h.Name).Append(", out object raw, ").Append(luaCallArgs).Append(") && raw is ").Append(h.ReturnTypeFullName).AppendLine(" typed)");
                    sb.AppendLine("                return typed;");
                    sb.Append("            return base.").Append(h.Name).Append('(').Append(baseCallArgs).AppendLine(");");
                    break;
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string ToSnakeCase(string pascal)
    {
        StringBuilder sb = new(pascal.Length + 8);
        for (int i = 0; i < pascal.Length; i++)
        {
            char c = pascal[i];
            if (char.IsUpper(c))
            {
                if (i > 0)
                    sb.Append('_');
                sb.Append(char.ToLowerInvariant(c));
            }
            else
            {
                sb.Append(c);
            }
        }
        return sb.ToString();
    }

    private enum HookReturnKind
    {
        Void,
        Bool,
        Int32,
        UInt32,
        Enum,
        CardList,
        TypedObject
    }

    private sealed record HookParamModel(string Name, string TypeFullName, bool IsEnum);

    private sealed record HookMethodModel(
        string Name,
        string FieldName,
        string SnakeName,
        HookReturnKind ReturnKind,
        string ReturnTypeFullName,
        ImmutableArray<HookParamModel> Parameters);

    private sealed record EnumMapModel(string LuaGlobalName, ImmutableArray<(string Name, int Value)> Members);

    private sealed record LuaBindingModel(
        ImmutableArray<HookMethodModel> Hooks,
        ImmutableArray<string> DefaultRules,
        ImmutableArray<EnumMapModel> Enums);
}
