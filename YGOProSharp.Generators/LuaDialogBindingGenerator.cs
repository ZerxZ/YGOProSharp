using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace YGOProSharp.Generators;

/// <summary>
/// Roslyn 增量源生成器：以 <c>WindBot.Game.AI.DialogsData</c> 为单一事实源，
/// 在编译期自动生成 <c>LuaDialogHookNames</c>、<c>LuaDialogScript.AllEventKeys</c> 与 <c>LuaDialogDsl</c> 事件绑定胶水。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LuaDialogBindingGenerator : IIncrementalGenerator
{
    private const string AttributeFullName = "WindBot.Game.AI.Lua.GenerateLuaDialogBindingsAttribute";

    private const string AttributeSource = """
        // <auto-generated />
        using System;

        namespace WindBot.Game.AI.Lua
        {
            [AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
            internal sealed class GenerateLuaDialogBindingsAttribute : Attribute
            {
            }
        }
        """;

    private static readonly Dictionary<string, (string PascalName, string HookConstName, string HookFuncName, string SnakeAlias)> KnownMeta =
        new(StringComparer.OrdinalIgnoreCase)
        {
            ["welcome"] = ("Welcome", "OnWelcome", "OnWelcome", "welcome"),
            ["deckerror"] = ("DeckError", "OnDeckError", "OnDeckError", "deck_error"),
            ["duelstart"] = ("DuelStart", "OnDuelStart", "OnDuelStart", "duel_start"),
            ["newturn"] = ("NewTurn", "OnNewTurn", "OnNewTurn", "new_turn"),
            ["endturn"] = ("EndTurn", "OnEndTurn", "OnEndTurn", "end_turn"),
            ["directattack"] = ("DirectAttack", "OnDirectAttackHook", "OnDirectAttack", "direct_attack"),
            ["attack"] = ("Attack", "OnAttack", "OnAttack", "attack"),
            ["ondirectattack"] = ("OnDirectAttack", "OnReceiveDirectAttack", "OnOnDirectAttack", "on_direct_attack"),
            ["activate"] = ("Activate", "OnActivate", "OnActivate", "activate"),
            ["summon"] = ("Summon", "OnSummon", "OnSummon", "summon"),
            ["setmonster"] = ("SetMonster", "OnSetMonster", "OnSetMonster", "set_monster"),
            ["chaining"] = ("Chaining", "OnChaining", "OnChaining", "chaining"),
            ["surrender"] = ("Surrender", "OnSurrender", "OnSurrender", "surrender"),
            ["custom"] = ("Custom", "OnCustom", "OnCustom", "custom")
        };

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static ctx =>
            ctx.AddSource("GenerateLuaDialogBindingsAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

        IncrementalValuesProvider<ImmutableArray<DialogEventModel>> models = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeFullName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => ExtractEvents(ctx))
            .Where(static arr => !arr.IsDefaultOrEmpty);

        context.RegisterSourceOutput(models, static (spc, events) =>
        {
            spc.AddSource("LuaDialogHookNames.g.cs", SourceText.From(EmitHookNames(events), Encoding.UTF8));
            spc.AddSource("LuaDialogBindings.g.cs", SourceText.From(EmitDialogBindings(events), Encoding.UTF8));
        });
    }

    private static ImmutableArray<DialogEventModel> ExtractEvents(GeneratorAttributeSyntaxContext ctx)
    {
        INamedTypeSymbol? dialogsData = ctx.SemanticModel.Compilation.GetTypeByMetadataName("WindBot.Game.AI.DialogsData");
        if (dialogsData is null)
            return ImmutableArray<DialogEventModel>.Empty;

        ImmutableArray<DialogEventModel>.Builder builder = ImmutableArray.CreateBuilder<DialogEventModel>();
        foreach (ISymbol member in dialogsData.GetMembers())
        {
            if (member is not IPropertySymbol prop ||
                prop.Type is not IArrayTypeSymbol arrType ||
                arrType.ElementType.SpecialType != SpecialType.System_String)
            {
                continue;
            }

            string key = prop.Name.ToLowerInvariant();
            if (KnownMeta.TryGetValue(key, out var meta))
            {
                builder.Add(new DialogEventModel(key, meta.PascalName, meta.HookConstName, meta.HookFuncName, meta.SnakeAlias));
            }
            else
            {
                string pascal = char.ToUpperInvariant(prop.Name[0]) + prop.Name.Substring(1);
                builder.Add(new DialogEventModel(key, pascal, "On" + pascal, "On" + pascal, key));
            }
        }

        return builder.ToImmutable();
    }

    private static string EmitHookNames(ImmutableArray<DialogEventModel> events)
    {
        StringBuilder sb = new(4096);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("namespace WindBot.Game.AI.Lua");
        sb.AppendLine("{");
        sb.AppendLine("    public static class LuaDialogHookNames");
        sb.AppendLine("    {");
        sb.AppendLine("        public const string FacedownMonsterName = \"facedownmonstername\";");
        foreach (DialogEventModel ev in events)
            sb.Append("        public const string ").Append(ev.PascalName).Append(" = \"").Append(ev.RawKey).AppendLine("\";");

        sb.AppendLine();
        sb.AppendLine("        public const string OnInit = \"OnInit\";");
        sb.AppendLine("        public const string OnDispose = \"OnDispose\";");
        sb.AppendLine("        public const string OnMessage = \"OnMessage\";");
        foreach (DialogEventModel ev in events)
            sb.Append("        public const string ").Append(ev.HookConstName).Append(" = \"").Append(ev.HookFuncName).AppendLine("\";");

        sb.AppendLine();
        sb.AppendLine("        public static bool TryNormalizeEventKey(string rawKey, out string normalized)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (string.IsNullOrWhiteSpace(rawKey)) { normalized = null; return false; }");
        sb.AppendLine("            string compact = rawKey.Trim().Replace(\"_\", string.Empty).Replace(\"-\", string.Empty).ToLowerInvariant();");
        sb.AppendLine("            switch (compact)");
        sb.AppendLine("            {");
        foreach (DialogEventModel ev in events)
        {
            sb.Append("                case ").Append(ev.PascalName).AppendLine(":");
            if (ev.RawKey == "ondirectattack")
                sb.AppendLine("                case \"receivedirectattack\":");
            sb.Append("                    normalized = ").Append(ev.PascalName).AppendLine("; return true;");
        }
        sb.AppendLine("                default: normalized = null; return false;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public static string GetHookNameForEvent(string eventKey) => eventKey switch");
        sb.AppendLine("        {");
        foreach (DialogEventModel ev in events)
            sb.Append("            ").Append(ev.PascalName).Append(" => ").Append(ev.HookConstName).AppendLine(",");
        sb.AppendLine("            _ => null");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string EmitDialogBindings(ImmutableArray<DialogEventModel> events)
    {
        StringBuilder sb = new(4096);
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("namespace WindBot.Game.AI.Lua");
        sb.AppendLine("{");
        sb.AppendLine("    public sealed partial class LuaDialogScript");
        sb.AppendLine("    {");
        sb.AppendLine("        private static readonly string[] AllEventKeys =");
        sb.AppendLine("        [");
        foreach (DialogEventModel ev in events)
            sb.Append("            LuaDialogHookNames.").Append(ev.PascalName).AppendLine(",");
        sb.AppendLine("        ];");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public sealed partial class LuaDialogDsl");
        sb.AppendLine("    {");
        sb.AppendLine("        private void BindGeneratedDialogEvents()");
        sb.AppendLine("        {");
        foreach (DialogEventModel ev in events)
        {
            if (ev.RawKey == ev.SnakeAlias)
                sb.Append("            BindEventLineHelpers(LuaDialogHookNames.").Append(ev.PascalName).Append(", \"").Append(ev.RawKey).AppendLine("\");");
            else
                sb.Append("            BindEventLineHelpers(LuaDialogHookNames.").Append(ev.PascalName).Append(", \"").Append(ev.RawKey).Append("\", \"").Append(ev.SnakeAlias).AppendLine("\");");
        }
        sb.AppendLine();
        sb.AppendLine("            BindHook(\"on_init\", LuaDialogHookNames.OnInit);");
        sb.AppendLine("            BindHook(\"on_dispose\", LuaDialogHookNames.OnDispose);");
        sb.AppendLine("            BindHook(\"on_message\", LuaDialogHookNames.OnMessage);");
        foreach (DialogEventModel ev in events)
        {
            sb.Append("            BindHook(\"on_").Append(ev.RawKey).Append("\", LuaDialogHookNames.").Append(ev.HookConstName).AppendLine(");");
            if (ev.SnakeAlias != ev.RawKey)
                sb.Append("            BindHook(\"on_").Append(ev.SnakeAlias).Append("\", LuaDialogHookNames.").Append(ev.HookConstName).AppendLine(");");
            if (ev.RawKey == "ondirectattack")
                sb.AppendLine("            BindHook(\"on_receive_direct_attack\", LuaDialogHookNames.OnReceiveDirectAttack);");
        }
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private sealed record DialogEventModel(
        string RawKey,
        string PascalName,
        string HookConstName,
        string HookFuncName,
        string SnakeAlias);
}
